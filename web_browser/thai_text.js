// thai_text.js -- a raw transcript -> the text Lyra reads: ำ for ํา, filler words in front dropped, numbers as
// digits, Thai words joined up. "ก็ปรับแอร์เป็นยี่สิบสี่องศา" -> "ปรับแอร์เป็น 24 องศา"
//
// The speech model writes Thai with no spaces, so words have to be found inside running text. Intl.Segmenter
// doesn't do that the same way in every browser (Firefox splits "ยี่สิบสี่องศา" into ยี่|สิบ|สี่อง|ศา), so this
// doesn't use it. A number word counts unless it sits inside a word that merely contains it (สามารถ, ห้าม,
// โกหก, เก้าอี้, หนึ่งร้อย ...); a filler in front counts unless the text starts with a word that merely begins
// with it (อ่าน, ก็อป ...). Those words are the entries of PyThaiNLP's words_th.txt (5.4.0, CC0-1.0), the
// dictionary of the newmm tokenizer that zipformer-CarCMD-TH's score.py splits transcripts with before it asks
// Lyra; on its 1,227 command transcripts this gives the same text for 1,221. NOT_NUMBERS leaves out entries a
// shorter one already covers, and EXTRA adds what a car needs that the dictionary lacks.

