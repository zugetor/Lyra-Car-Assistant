/** Raw transcript -> what Lyra reads (the same steps score.py takes before asking Lyra). */
export function textForLyra(raw) {
  const text = dropFillers(raw.replace(/ํา/g, "ำ").trim());
  return numbersToDigits(text).replace(/\s+/g, " ").replace(/(?<=[\u0E00-\u0E7F])\s+(?=[\u0E00-\u0E7F])/g, "").trim();
}

/** ก็, แล้วก็, อืม, เอ่อ, อ่า, เออ in front, which the model sometimes writes, dropped while something follows. */
export function dropFillers(text) {
  for (;;) {
    const f = FILLERS.find((w) => text.startsWith(w));
    if (!f || NOT_FILLERS.some((w) => text.startsWith(w)) || !text.slice(f.length).trim()) return text;
    text = text.slice(f.length).trim();
  }
}

// at one spot a NOT_NUMBERS word wins over a number word, the longest first
const SCAN = new RegExp(`(${[...NOT_NUMBERS, ...EXTRA].sort((a, b) => b.length - a.length).join("|")})|(${WORDS.join("|")})`, "g");
const MARK = /[\u0E30-\u0E3A\u0E47-\u0E4E]/;    // a vowel or tone mark right after: the word goes on (สามี)
const LEAD = /[\u0E40-\u0E44]/;                  // เ แ โ ใ ไ right before: it started earlier (แหก)

/** "ยี่สิบสี่" -> "24", "สิบเจ็ด" -> "17", "สอง" -> "2" (words as an array). */
export function thaiNumber(words) {
  const i = words.indexOf("สิบ");
  if (i >= 0) {
    const tens = i ? (DIGIT[words[i - 1]] ?? 1) : 1, units = i + 1 < words.length ? (DIGIT[words[i + 1]] ?? 0) : 0;
    return String(tens * 10 + units);
  }
  return words.filter((w) => w in DIGIT).map((w) => DIGIT[w]).join("");
}

/** Every run of number words in `text` replaced by " <digits> "; the rest of the text is left as it was. */
export function numbersToDigits(text) {
  const runs = [];
  let run = null;
  for (const m of text.matchAll(SCAN)) {
    if (m[1]) { run = null; continue; }
    if (run && run.end === m.index) { run.words.push(m[2]); run.end += m[2].length; }
    else runs.push(run = { start: m.index, end: m.index + m[2].length, words: [m[2]] });
  }
  let out = "", at = 0;
  for (const r of runs) {
    if (MARK.test(text[r.end] || "") || LEAD.test(text[r.start - 1] || "")) continue;
    out += `${text.slice(at, r.start)} ${thaiNumber(r.words)} `;
    at = r.end;
  }
  return out + text.slice(at);
}
